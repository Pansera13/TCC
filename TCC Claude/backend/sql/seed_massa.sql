select categoria, count(*) as produtos,
       count(*) filter (where quantidade = 0) as zerados
from products group by categoria order by categoria;

-- Conferencia: deve retornar 0 divergentes
select count(*) as divergentes
from products p
where p.quantidade <> coalesce((select sum(m.quantidade) from movements m
                                where m.product_id = p.id and m.tipo = 'entrada'), 0);
